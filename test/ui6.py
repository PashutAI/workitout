from playwright.sync_api import sync_playwright
import json
errs=[]
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    pg=b.new_page(viewport={'width':390,'height':844},accept_downloads=True)
    pg.on('pageerror',lambda e:errs.append('PE '+str(e)))
    pg.route('https://api.anthropic.com/**',lambda r:r.fulfill(status=200,headers={'access-control-allow-origin':'*','content-type':'application/json'},body=json.dumps({'content':[{'type':'text','text':'{"questions":[],"areas":[],"diet":[],"calorie_adjust":0,"coach_note":"ok"}'}]})))
    pg.goto('file:///home/claude/workitout/dist/index.html'); pg.wait_for_timeout(1200)
    print('home: ai card',pg.locator('#ai-key').count(),'data card',pg.locator('text=Download backup').count(),'| notice:',pg.locator('.notice').first.inner_text())
    pg.screenshot(path='/tmp/h1.png')
    pg.locator('a.gear').click(); pg.wait_for_timeout(300)
    print('hash',pg.evaluate('location.hash'),'| settings ai',pg.locator('#ai-key').count(),'backup',pg.locator('text=Download backup').count(),'restore',pg.locator('text=Restore from backup').count())
    pg.screenshot(path='/tmp/settings.png',full_page=True)
    pg.fill('#ai-key','sk-ant-test'); pg.get_by_text('Save key').click(); pg.wait_for_timeout(200)
    pg.locator('.back').first.click(); pg.wait_for_timeout(300)
    print('after key, notice:',pg.locator('.notice').first.inner_text())
    pg.get_by_role('button', name='Reconsult').first.click(); pg.wait_for_timeout(300)
    pg.locator('button.accent',has_text='Consult').click(); pg.wait_for_timeout(2500)
    if pg.evaluate("window.__WO_DEBUG.C.step")=='questions': pg.locator('button',has_text='Skip').click(); pg.wait_for_timeout(400)
    pg.get_by_role('button',name='Confirm plan').click(); pg.wait_for_timeout(300)
    pg.get_by_text('Yes, replace').click(); pg.wait_for_timeout(500)
    print('after reconsult, notice count:',pg.locator('.notice:has-text("sample program")').count(), '| isDefault:',pg.evaluate('window.__WO_DEBUG.S.docs.plan.isDefault'))
    pg.reload(); pg.wait_for_timeout(1000)
    print('after reload, sample notice:',pg.locator('text=sample program').count())
    # import a backup marked isDefault:true
    bk=json.load(open('/home/claude/workitout-backup-personal.json'))
    pg.evaluate("localStorage.removeItem('workitout.v1.anon')"); pg.reload(); pg.wait_for_timeout(1000)
    print('fresh: sample notice',pg.locator('text=sample program').count())
    pg.locator('a.gear').click(); pg.wait_for_timeout(300)
    pg.locator('input[type=file]').set_input_files('/home/claude/workitout-backup-personal.json'); pg.wait_for_timeout(300)
    pg.get_by_text('Yes, restore').click(); pg.wait_for_timeout(600)
    print('after import: hash',pg.evaluate('location.hash'),'sample notice',pg.locator('text=sample program').count(),'| goal',pg.locator('h1.goal').inner_text())
    b.close()
print('\n'.join(errs) or 'no errors')
